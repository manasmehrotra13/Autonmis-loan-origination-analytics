-- Monthly Loan Applications & Approval Rate
-- Objective: To analyze monthly loan application volumes and approval rates, providing insights into overall application success trends and operational efficiency.
SELECT
  TO_CHAR(DATE_TRUNC('month', bi.applied_date), 'MM') AS application_month,
  cast(COUNT(fj.loan_id)as int) AS total_applications,
  cast(COUNT(CASE WHEN fj.approval_status = 'Approved' THEN 1 END)as int) AS approved_count,
  cast(ROUND(100.0 * COUNT(CASE WHEN fj.approval_status = 'Approved' THEN 1 END) / COUNT(fj.loan_id), 2)as float) AS approval_rate
FROM los_fact_loan_journey fj
JOIN los_dim_business_insights bi ON fj.loan_id = bi.loan_id
GROUP BY application_month
ORDER BY application_month;


-- Average Loan Amount and Interest Rate by Loan Type
-- Objective: To evaluate the average loan amount and interest rate for each loan type on a monthly basis, enabling assessment of product performance and pricing trends.
SELECT
  bi.loan_type,
  TO_CHAR(DATE_TRUNC('month', bi.applied_date), 'MM') AS applied_month,
  cast(round(AVG(fj.loan_amount),2)as float) AS avg_loan_amount,
  cast(round(AVG(fj.applied_interest_rate),2)as float) AS avg_interest_rate
FROM los_fact_loan_journey fj
JOIN los_dim_business_insights bi ON fj.loan_id = bi.loan_id
GROUP BY bi.loan_type, applied_month
ORDER BY applied_month;


-- Top 10 Agents by Loan Applications Submitted
-- Objective: Identify the top 10 agents by loan applications submitted to evaluate agent performance and optimize resource allocation.
SELECT
    TO_CHAR(DATE_TRUNC('month', dbi.applied_date), 'YYYY-MM-DD') AS applied_dates,
    CONCAT(dbi.agent_first_name, ' ', dbi.agent_last_name) AS agent_name,
    cast(COUNT(flj.application_id)as int) AS total_applications
FROM los_fact_loan_journey flj
JOIN los_dim_business_insights dbi ON flj.agent_id = dbi.agent_id
GROUP BY applied_dates, agent_name
ORDER BY total_applications DESC
LIMIT 10;


-- Loan Decline Reasons Breakdown
-- Objective: Analyze loan decline reasons to identify common rejection factors and enhance approval strategies while mitigating risk.
SELECT
    dbi.reason_name,
    cast(COUNT(flj.decline_id)as int) AS total_declines,
    cast(ROUND(AVG(flj.credit_score_at_decline), 2)as float) AS avg_credit_score_at_decline,
    cast(ROUND(AVG(flj.income_at_decline), 2)as float) AS avg_income_at_decline
FROM los_fact_loan_journey flj
JOIN los_dim_business_insights dbi ON flj.decline_reason_id = dbi.reason_id
WHERE flj.approval_status = 'Declined'
GROUP BY dbi.reason_name
ORDER BY  total_declines DESC;


-- Revenue Generated by Region
-- Objective: Assess revenue generated by region to identify high-performing locations and optimize market expansion strategies.
SELECT
    dbi.state,
    cast(ROUND(SUM(dbi.revenue_generated), 2)as float) AS total_revenue
FROM los_dim_business_insights dbi
GROUP BY dbi.state
ORDER BY total_revenue asc;


-- Agent Performance Analysis
-- Objective: Evaluate agent performance based on applications submitted, revenue generated, experience, and ratings to enhance productivity and incentive strategies.
SELECT
    TO_CHAR(DATE_TRUNC('month', dbi.applied_date), 'YYYY-MM-DD') AS applied_dates,
    CONCAT(dbi.agent_first_name, ' ', dbi.agent_last_name) AS agent_name,
    dbi.performance_rating,
    dbi.experience_years,
    COUNT(flj.application_id) AS total_applications,
    cast(SUM(dbi.revenue_generated)as float) AS total_revenue
FROM los_fact_loan_journey flj
JOIN los_dim_business_insights dbi ON flj.agent_id = dbi.agent_id
GROUP BY applied_dates, agent_name, dbi.performance_rating, dbi.experience_years
ORDER BY total_revenue DESC
limit 10;


-- Application Decline Trends Over Time
-- Objective: To track monthly application volumes and analyze the decline rate percentage over time, helping identify trends in loan application rejections.
SELECT
    TO_CHAR(DATE_TRUNC('month', flj.disbursement_date), 'MM') AS month,
    cast(COUNT(flj.application_id)as int) AS total_applications,
    cast(COUNT(CASE WHEN flj.approval_status = 'Declined' THEN 1 END)as int) AS total_declines,
    cast(ROUND(
        100.0 * COUNT(CASE WHEN flj.approval_status = 'Declined' THEN 1 END)
        / COUNT(flj.application_id),
    2)as float) AS decline_rate_percentage
FROM los_fact_loan_journey flj
GROUP BY month
ORDER BY month;


-- Customer Credit Score Distribution
-- Objective: Categorize customers based on credit scores to assess risk distribution and tailor lending strategies.
SELECT
    CASE
        WHEN cust_credit_score < 600 THEN 'Poor'
        WHEN cust_credit_score BETWEEN 600 AND 700 THEN 'Fair'
        WHEN cust_credit_score BETWEEN 700 AND 800 THEN 'Good'
        ELSE 'Excellent'
    END AS credit_category,
    cast(COUNT(*)as int) AS total_customers
FROM los_dim_customer_details
GROUP BY credit_category;


-- Loan Disbursement Trends Over Time
-- Objective: Analyze loan disbursement trends over time to identify seasonal patterns and optimize lending strategies.
SELECT
    TO_CHAR(DATE_TRUNC('month', flj.disbursement_date), 'MM') AS month,
    cast(SUM(flj.disbursed_amount)as float) AS total_disbursed_amount
FROM los_fact_loan_journey flj
WHERE flj.disbursement_date IS NOT NULL
GROUP BY month
ORDER BY month;


-- Employment Status Distribution
-- Objective: To analyze the distribution of customers by employment status and identify their proportional share in the overall borrower base.
SELECT
    cust_employment_status AS employment_status,
    cast(COUNT(customer_id)as int) AS total_customers,
    cast(ROUND(100.0 * COUNT(customer_id) / SUM(COUNT(customer_id)) OVER (), 2)as float) AS percentage_share
FROM los_dim_customer_details
GROUP BY cust_employment_status
ORDER BY total_customers DESC;


-- Most Popular Loan Amount Brackets
-- Objective: Identify the most popular loan amount brackets to understand customer borrowing preferences and optimize loan product offerings.
SELECT
    CASE
        WHEN loan_amount_requested < 7000 THEN 'Less than 7K'
        WHEN loan_amount_requested BETWEEN 7000 AND 21000 THEN '7K-21K'
        WHEN loan_amount_requested BETWEEN 21000 AND 35000 THEN '21K-35K'
        ELSE 'More than 50K'
    END AS loan_bracket,
    cast(COUNT(*)as int) AS total_loans
FROM los_fact_loan_journey
GROUP BY loan_bracket
ORDER BY total_loans DESC;


-- Customer Feedback Score Distribution
-- Objective: Analyze customer feedback score distribution to measure satisfaction levels and identify areas for service improvement.
SELECT
    cast(feedback_score as text),
    cast(COUNT(*)as int) AS total_customers
FROM los_dim_customer_details
GROUP BY feedback_score
ORDER BY feedback_score DESC;
